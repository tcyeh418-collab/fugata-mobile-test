export function createShuffledFragments(random = Math.random) {
  const shuffled = AUDIO_DEFINITIONS.map((item) => ({ ...item }));
  for (let index = shuffled.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(random() * (index + 1));
    [shuffled[index], shuffled[swapIndex]] = [shuffled[swapIndex], shuffled[index]];
  }

  return shuffled.map((definition, index) => {
    const pedestal = PEDESTALS[index];
    return {
      ...definition,
      pedestalId: pedestal.id,
      displayLabel: `旋律片段 ${index + 1}`,
      x: pedestal.x,
      y: pedestal.y,
      interactionRadius: pedestal.interactionRadius,
      isPlaying: false,
      isHeld: false,
      originalPosition: { x: pedestal.x, y: pedestal.y },
    };
  });
}

export function createShuffledEchoTowers(random = Math.random) {
  const shuffled = ANSWER_DEFINITIONS.map((item) => ({ ...item }));
  for (let index = shuffled.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(random() * (index + 1));
    [shuffled[index], shuffled[swapIndex]] = [shuffled[swapIndex], shuffled[index]];
  }

  return shuffled.map((definition, index) => {
    const position = ECHO_TOWER_POSITIONS[index];
    return {
      ...definition,
      pedestalId: position.id,
      displayLabel: `回應塔 ${index + 1}`,
      x: position.x,
      y: position.y,
      interactionRadius: 66,
      isPlaying: false,
      isSelected: false,
      isConnected: false,
      visualLevel: 0,
      cablePath: position.path.map(([x, y]) => ({ x, y })),
    };
  });
}

export function setMessage(state, lines, duration = 2.2, kind = "status") {
  const room03Transient = state.gameProgress.currentRoom === 3;
  const resolvedDuration = room03Transient ? 1.5 : duration;
  state.ui.message = {
    room: state.gameProgress.currentRoom,
    lines,
    remaining: resolvedDuration,
    duration: resolvedDuration,
    fadeDuration: room03Transient && !state.ui.reducedMotion ? 0.3 : 0,
    alpha: 1,
    kind,
  };
}

export function heldFragment(state) {
  return state.fragments.find((fragment) => fragment.id === state.gameProgress.heldFragmentId) ?? null;
}
